interface StatCardProps {
  value: string;
  label: string;
  sublabel: string;
  styles: ReturnType<typeof createStyles>;
  icon: React.ComponentProps<typeof Ionicons>['name'];
  color: string;
  tint: string;
  comparison?: string;
  onPress?: () => void;
}

const StatCard: React.FC<StatCardProps> = ({ value, label, sublabel, styles, icon, color, tint, comparison, onPress }) => {
  const trend = comparison?.startsWith('+') ? 'up' : comparison?.startsWith('−') ? 'down' : 'neutral';
  const Container = onPress ? TouchableOpacity : View;
  return (
  <Container
    style={styles.statCard}
    onPress={onPress}
    accessibilityRole={onPress ? 'button' : undefined}
    accessibilityLabel={onPress ? `Ver ${label.toLowerCase()}` : undefined}
    accessibilityHint={onPress ? `${value}. ${sublabel}. Muestra las facturas pendientes de cobro.` : undefined}
  >
    <View style={[styles.statIcon, { backgroundColor: tint }]}><Ionicons name={icon} size={19} color={color} /></View>
    <View style={styles.statContent}>
    <View style={styles.statTopline}>
    <Text style={[styles.statValue, { color }]}>{value}</Text>
    {comparison && <View style={[styles.statComparison, trend === 'up' ? styles.trendUp : trend === 'down' ? styles.trendDown : styles.trendNeutral]}>
      <Text style={[styles.statComparisonText, trend === 'up' ? styles.trendUpText : trend === 'down' ? styles.trendDownText : styles.trendNeutralText]}>{trend === 'up' ? '↗ ' : trend === 'down' ? '↘ ' : ''}{comparison}</Text>
    </View>}
    </View>
    <Text style={styles.statLabel}>{label}</Text>
    <Text style={styles.statSublabel}>{sublabel}</Text>
    {onPress && <Text style={styles.statLinkText}>Ver pendientes →</Text>}
    </View>
  </Container>
  );
};

